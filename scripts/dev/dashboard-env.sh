#!/usr/bin/env bash
# v2-P0.2: write dashboard/.env.local from the root .env so `cd dashboard && npm run dev` works on its own.
# The file is git-ignored (dashboard/.gitignore: .env*). Re-run after changing the root .env.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
[ -f .env ] || { echo "no .env yet: run npm run setup first"; exit 1; }
set -a; . ./.env; set +a
out=dashboard/.env.local
{
  echo "# generated by scripts/dev/dashboard-env.sh from the root .env: do not edit, do not commit"
  echo "AUTH_SECRET=${AUTH_SECRET:-}"
  echo "GITHUB_CLIENT_ID=${GITHUB_CLIENT_ID:-}"
  echo "GITHUB_CLIENT_SECRET=${GITHUB_CLIENT_SECRET:-}"
  echo "SEISMO_API_URL=${SEISMO_API_URL:-http://localhost:${PORT:-4000}}"
  echo "SERVICES_URL=${SERVICES_URL:-http://localhost:${SERVICES_PORT:-4100}}"
  echo "DEMO_ADMIN_TOKEN=${DEMO_ADMIN_TOKEN:-}"
  echo "DEMO_MODE=${DEMO_MODE:-true}"
  echo "NEXT_PUBLIC_USE_MOCKS=${NEXT_PUBLIC_USE_MOCKS:-0}"
} > "$out"
chmod 600 "$out"
echo "wrote $out"
